const {chromium} = require('playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
    const browser = await chromium.launch({headless:true,executablePath:process.env.BROWSER_EXECUTABLE});
    try {
        const page = await browser.newPage({viewport:{width:1440,height:900}});
        const errors = [];
        let scope = 'user:session1';
        page.on('pageerror', error => errors.push(error.message));
        await page.route('**/*', route => {
            const url = new URL(route.request().url());
            if (url.pathname === '/tabs.js') return route.fulfill({contentType:'text/javascript',body:fs.readFileSync('public/js/workspace-tabs.js','utf8')});
            if (url.pathname === '/tabs.css') return route.fulfill({contentType:'text/css',body:fs.readFileSync('public/css/workspace-tabs.css','utf8')});
            if (url.pathname === '/logout') return route.fulfill({body:'Logged out'});
            return route.fulfill({contentType:'text/html',body:`<style>:root{--topbar:60px;--green:#203f62}*{box-sizing:border-box;margin:0}header{height:60px;background:var(--green);color:white;padding:15px}main{min-height:150vh}</style><link rel="stylesheet" href="/tabs.css"><header>PRINŻ · Projekt testowy</header><nav data-workspace-tabs class="workspace-tabs" data-scope="${scope}" data-title="Strona ${url.pathname}" data-section="${url.pathname === '/crm' ? 'tasks' : ''}" data-logout="http://localhost/logout" hidden><div class="workspace-tabs-items" data-workspace-tabs-items></div></nav><main><form id="logout" method="post" action="/logout"><button>Wyloguj</button></form><input id="draft" value="Niezapisana treść"><a href="/projects/99">Zwykła nawigacja</a></main><script src="/tabs.js" defer></script>`});
        });
        const tabs = () => page.locator('.workspace-tab');
        const saved = () => page.evaluate(() => JSON.parse(sessionStorage.getItem('workspace-tabs:'+document.querySelector('[data-workspace-tabs]').dataset.scope)||'[]'));
        for (let i=1;i<=10;i++) await page.goto('http://localhost/projects/'+i);
        assert.equal(await tabs().count(),10);
        await page.goto('http://localhost/projects/1?tab=finance#details');
        assert.equal((await saved())[0].url,'/projects/1?tab=finance#details');
        await page.goto('http://localhost/projects/11');
        assert.equal(await tabs().count(),10);
        assert.equal((await saved())[0].key,'/projects/2');
        await page.reload(); assert.equal(await tabs().count(),10);
        await page.locator('.is-active button').click();
        await page.goto('http://localhost/projects/10');
        assert.ok(!(await saved()).some(row=>row.key==='/projects/11'));
        await page.goto('http://localhost/projects/11/edit'); assert.equal(await tabs().count(),10);
        await page.goto('http://localhost/crm');
        await page.goto('http://localhost/crm?tab=tasks');
        assert.equal((await saved()).filter(row=>row.key.startsWith('/crm')).length,1);
        await page.goto('http://localhost/crm?tab=pipeline');
        assert.equal((await saved()).filter(row=>row.key.startsWith('/crm')).length,2);
        await page.evaluate(() => history.replaceState(null,'','/crm?tab=pipeline&q=test#lead'));
        await page.goto('http://localhost/projects/12');
        assert.ok((await saved()).some(row=>row.url==='/crm?tab=pipeline&q=test#lead'));
        await page.screenshot({path:'tmp/workspace-tabs-desktop.png'});
        await page.setViewportSize({width:390,height:844});
        assert.ok(await page.locator('nav').evaluate(e=>e.getBoundingClientRect().width<=390));
        await page.screenshot({path:'tmp/workspace-tabs-mobile.png'});
        const count = await tabs().count();
        await tabs().first().locator('button').click(); assert.equal(await tabs().count(),count-1);
        // Navigation remains native: existing unsaved-form guards can cancel it.
        await page.locator('#draft').fill('Zmieniona treść');
        await page.evaluate(()=>window.addEventListener('beforeunload',event=>{event.preventDefault();event.returnValue='';}));
        page.once('dialog', dialog=>dialog.dismiss());
        await tabs().first().locator('a').click({noWaitAfter:true});
        await page.waitForTimeout(150);
        assert.equal(await page.locator('#draft').inputValue(),'Zmieniona treść');
        await page.evaluate(()=>window.dispatchEvent(new Event('session:expired')));
        assert.equal(await tabs().count(),0);
        assert.deepEqual(await saved(),[]);
        page.once('dialog', dialog=>dialog.accept());
        await page.goto('http://localhost/projects/13');
        scope = 'user:session2';
        await page.reload(); assert.equal(await tabs().count(),1);
        assert.equal(await page.evaluate(()=>sessionStorage.getItem('workspace-tabs:user:session1')),null);
        await page.locator('#logout button').click();
        await page.waitForURL('**/logout');
        assert.equal(await page.evaluate(()=>sessionStorage.getItem('workspace-tabs:user:session2')),null);
        await page.goto('http://localhost/projects/14');
        await page.evaluate(()=>sessionStorage.setItem('workspace-tabs:user:session2',JSON.stringify([{url:'https://evil.example/test',title:'External'},{url:'javascript:alert(1)',title:'Script'},{url:'/projects/22?token=secret',title:'<img src=x onerror=alert(1)>'}])));
        await page.evaluate(()=>window.dispatchEvent(new PageTransitionEvent('pageshow',{persisted:true})));
        assert.ok((await saved()).some(row=>row.url==='/projects/22'));
        assert.equal(await page.locator('.workspace-tab img').count(),0);
        assert.ok((await saved()).every(row=>!row.url.includes('secret')&&!row.url.includes('evil')));
        assert.deepEqual(errors,[]);
        console.log('PASS: 10 tabs FIFO, no duplicate records, module sections, latest URL, close, reload, narrow screen, unsaved guard, session expiry/logout/login isolation, unsafe URL and HTML filtering.');
    } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
